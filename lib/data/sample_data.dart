/// 샘플 40병을 넣습니다. 이미 넣었으면 먼저 지우고 다시 넣습니다.
Future<int> addSampleWhiskies(NoteStore store) async {
  await removeSampleWhiskies(store);
  final rnd = math.Random(7);
  int r(int lo, int hi) => lo + rnd.nextInt(hi - lo + 1);
  final now = DateTime.now();
  var i = 0;
  // 뒤에서부터 넣어야 진열장에 목록 순서대로 섭니다 (새 병이 맨 앞).
  for (final (index, s) in _samples.indexed.toList().reversed) {
    final (name, type, origin, sub, age, abv, price, score, color) = s;
    final peated = sub == 'Islay' || name.contains('Peat');
    final sherry = age.contains('Sherry') || age.contains('Oloroso');
    // 같은 이름이 둘이면 목록에서 먼저 나온 병만 빈 병으로
    final firstOfName = _samples.indexWhere((x) => x.$1 == name) == index;
    final stories = firstOfName ? _emptied[name] : null;
    final created = now.subtract(Duration(days: 30 + i * 9));
    await store.upsert(
      TastingNote(
        id: '$samplePrefix${i++}',
        name: name,
        type: type,
        origin: origin,
        subRegion: sub,
        ageCask: age,
        abv: abv,
        price: price,
        score: score,
        color: color,
        nose: [
          r(2, 6),
          r(3, sherry ? 9 : 7),
          r(1, 6),
          r(3, 7),
          peated ? r(7, 10) : r(0, 2),
          r(3, 7),
          r(2, 6),
          r(0, 3),
        ],
        palate: [
          r(4, 8),
          r(1, 4),
          peated ? r(3, 6) : r(0, 3),
          r(1, 4),
          r(2, 6),
          r(1, 5),
        ],
        retronasal: [
          r(1, 5),
          r(2, sherry ? 8 : 6),
          r(1, 5),
          r(3, 7),
          peated ? r(6, 10) : r(0, 2),
          r(2, 6),
          r(2, 6),
          r(0, 3),
        ],
        characters: {
          'dryOily': r(3, 7),
          'lightHeavy': sherry || peated ? r(5, 8) : r(2, 6),
          'mildSpicy': r(2, 7),
          'smoothIntense': abv > 48 ? r(6, 9) : r(2, 6),
        },
        finish: r(3, 9),
        overall: score >= 88 ? '다시 사고 싶은 병.' : '',
        emptiedAt: stories == null
            ? null
            : now.subtract(Duration(days: r(3, 200))),
        stories: [
          for (final (j, (text, who)) in (stories ?? const []).indexed)
            StoryEntry(
              id: '$samplePrefix$i-story-$j',
              date: created.add(Duration(days: 10 + j * 25)),
              text: text,
              companions: who,
            ),
        ],
        createdAt: created,
      ),
    );
  }
  return i;
}

/// 샘플로 넣은 병만 지웁니다 (직접 넣은 병은 그대로).
Future<int> removeSampleWhiskies(NoteStore store) async {
  final ids = store.notes
      .where((n) => n.id.startsWith(samplePrefix))
      .map((n) => n.id)
      .toList();
  for (final id in ids) {
    await store.delete(id);
  }
  return ids.length;
}
